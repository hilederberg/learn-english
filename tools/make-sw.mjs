// Generates sw.js with a precache list of every static file. Run: npm run sw
import { readdirSync, statSync, writeFileSync, readFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('..', import.meta.url));
const SKIP = new Set(['node_modules', '.git', 'tests', 'tools', '.github', 'sw.js', 'package.json', 'package-lock.json', 'README.md', 'CLAUDE.md', 'TASK.md']);
const files = [];
(function walk(dir) {
  for (const n of readdirSync(dir)) {
    if (SKIP.has(n) || n.startsWith('.')) continue;
    const p = join(dir, n); const st = statSync(p);
    if (st.isDirectory()) walk(p); else files.push('./' + relative(root, p).split('\\').join('/'));
  }
})(root);
files.sort();
const h = createHash('sha1'); h.update(readFileSync(fileURLToPath(import.meta.url))); for (const f of files) { h.update(f); h.update(readFileSync(join(root, f))); }
const version = h.digest('hex').slice(0, 10);
// Media (voice clips, fonts) never change under the same name: they live in a cache that survives updates,
// so an update only downloads what is new, and one failed clip never blocks the update.
const isMedia = f => /\.(mp3|woff2)$/.test(f);
const core = ['./'].concat(files.filter(f => !isMedia(f))), media = files.filter(isMedia);
const src = `// AUTO-GENERATED by tools/make-sw.mjs. Do not edit by hand.
const CACHE = 'english-${version}', MEDIA = 'english-media';
const FILES = ${JSON.stringify(core, null, 1)};
const MEDIA_FILES = ${JSON.stringify(media, null, 1)};
const isMedia = p => /\\.(mp3|woff2)$/.test(p);
self.addEventListener('install', e => { e.waitUntil(Promise.all([
  caches.open(CACHE).then(c => c.addAll(FILES.map(u => new Request(u, { cache: 'reload' })))),
  caches.open(MEDIA).then(c => Promise.allSettled(MEDIA_FILES.map(async u => { if (!(await c.match(u))) { const r = await fetch(u); if (r.ok) await c.put(u, r); } }))),
]).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => { e.waitUntil((async () => {
  for (const k of await caches.keys()) if (k !== CACHE && k !== MEDIA) await caches.delete(k);
  const keep = new Set(MEDIA_FILES.map(u => new URL(u, location).href)), m = await caches.open(MEDIA);
  for (const r of await m.keys()) if (!keep.has(r.url)) await m.delete(r);
  await self.clients.claim();
})()); });
self.addEventListener('fetch', e => {
  const req = e.request; if (req.method !== 'GET') return;
  const url = new URL(req.url); if (url.origin !== location.origin) return;
  if (isMedia(url.pathname)) { e.respondWith(caches.open(MEDIA).then(async c => (await c.match(req, { ignoreSearch: true })) || fetch(req).then(r => { if (r && r.ok) c.put(req, r.clone()); return r; }))); return; }
  e.respondWith(caches.open(CACHE).then(async c => {
    const hit = await c.match(req, { ignoreSearch: true });
    const net = fetch(req).then(r => { if (r && r.ok) c.put(req, r.clone()); return r; }).catch(() => null);
    if (hit) { e.waitUntil(net); return hit; }
    return (await net) || (req.mode === 'navigate' ? c.match('./') : Response.error());
  }));
});
`;
writeFileSync(join(root, 'sw.js'), src);
console.log('sw.js:', core.length, 'core +', media.length, 'media files, version', version);
